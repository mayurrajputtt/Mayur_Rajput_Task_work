function makeMdCell(text) {
  return {
    cell_type: "markdown",
    metadata: {},
    source: Array.isArray(text) ? text.map((t, i) => i === text.length - 1 ? t : t + "\n") : text.split("\n").map((t, i, arr) => i === arr.length - 1 ? t : t + "\n")
  };
}

function makeCodeCell(code) {
  return {
    cell_type: "code",
    execution_count: null,
    metadata: {},
    outputs: [],
    source: Array.isArray(code) ? code.map((c, i) => i === code.length - 1 ? c : c + "\n") : code.split("\n").map((c, i, arr) => i === arr.length - 1 ? c : c + "\n")
  };
}

